const db = require('../db');

console.log('🔧 Миграция FAQ...\n');

db.exec(`
  CREATE TABLE IF NOT EXISTS faq (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (datetime('now'))
  );
`);

console.log('✅ Таблица faq создана');

// Демо-вопросы
const count = db.prepare('SELECT COUNT(*) as c FROM faq').get().c;

if (count === 0) {
  const insert = db.prepare(`
    INSERT INTO faq (question, answer, sort_order, is_active)
    VALUES (?, ?, ?, 1)
  `);

  insert.run(
    'Сколько ждать заказ?',
    'Стандартный срок — 24 часа. Индивидуальные торты (по конструктору) — 48 часов. Для крупных заказов — уточняйте у менеджера.',
    1
  );

  insert.run(
    'Можно ли заказать торт по своему дизайну?',
    'Да! Используйте конструктор торта — соберите форму, вес, начинку и декор. Если нужен особый дизайн — напишите в комментарии к заказу или свяжитесь с нами.',
    2
  );

  insert.run(
    'Как оплатить заказ?',
    'Двумя способами: при получении (наличными или картой курьеру) или онлайн (ссылка на оплату придёт после подтверждения заказа менеджером).',
    3
  );

  insert.run(
    'Доставляете ли вы в другие города?',
    'Мы работаем по Москве и Московской области. Доставка рассчитывается индивидуально — от 300 ₽ в зависимости от адреса. Бесплатно от 3000 ₽.',
    4
  );

  insert.run(
    'Что делать, если торт не понравился?',
    'Мы отвечаем за качество: если что-то не так — свяжитесь с нами в течение 24 часов после получения. Заменим или вернём деньги.',
    5
  );

  insert.run(
    'Есть ли у вас безглютеновые / безлактозные торты?',
    'Да, можем сделать под заказ. Уточните в комментарии к заказу или свяжитесь с нами заранее — обсудим состав и цену.',
    6
  );

  console.log('✅ Добавлено 6 демо-вопросов');
} else {
  console.log(`ℹ️  FAQ уже: ${count} — пропускаем демо`);
}

console.log('\n🎉 Миграция FAQ завершена!');